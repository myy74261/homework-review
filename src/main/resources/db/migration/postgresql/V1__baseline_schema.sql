CREATE TABLE ai_review_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) with time zone NOT NULL,
    model varchar(100) NOT NULL,
    submission_id bigint NOT NULL,
    summary oid NOT NULL
);
CREATE INDEX idx_ai_review_runs_submission ON ai_review_runs (submission_id);

CREATE TABLE ai_review_suggestions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) with time zone NOT NULL,
    decided_at timestamp(6) with time zone,
    evidence_quote oid NOT NULL,
    rubric_name varchar(100) NOT NULL,
    run_id bigint NOT NULL,
