CREATE TABLE accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) with time zone NOT NULL,
    display_name varchar(80) NOT NULL,
    password_hash varchar(100) NOT NULL,
    role varchar(20) NOT NULL,
    student_number varchar(40),
    username varchar(60) NOT NULL,
    department varchar(100),
    email varchar(120),
    professional_title varchar(100),
    active boolean,
    deactivated_at timestamp(6) with time zone,
    CONSTRAINT uk_accounts_username UNIQUE (username)
);

CREATE TABLE classrooms (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_name varchar(100) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    join_code varchar(12) NOT NULL,
    name varchar(100) NOT NULL,
    teacher_id bigint NOT NULL,
    dissolved_at timestamp(6) with time zone,
    end_at timestamp(6) with time zone,
    start_at timestamp(6) with time zone,
    collaboration_enabled boolean,
    CONSTRAINT uk_classrooms_join_code UNIQUE (join_code)
);
CREATE INDEX idx_classrooms_teacher ON classrooms (teacher_id);

CREATE TABLE classroom_collaborators (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id bigint NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    invited_by_teacher_id bigint NOT NULL,
    teacher_id bigint NOT NULL,
    CONSTRAINT uk_classroom_collaborator_teacher UNIQUE (classroom_id, teacher_id)
);
CREATE INDEX idx_collaborators_teacher ON classroom_collaborators (teacher_id);

CREATE TABLE classroom_memberships (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id bigint NOT NULL,
    joined_at timestamp(6) with time zone NOT NULL,
    student_id bigint NOT NULL,
    CONSTRAINT uk_membership_classroom_student UNIQUE (classroom_id, student_id)
);
CREATE INDEX idx_memberships_student ON classroom_memberships (student_id);

CREATE TABLE classroom_roster_entries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id bigint NOT NULL,
    imported_at timestamp(6) with time zone NOT NULL,
    student_account_id bigint,
    student_name varchar(80) NOT NULL,
    student_number varchar(40) NOT NULL,
    CONSTRAINT uk_roster_classroom_student_number UNIQUE (classroom_id, student_number)
);
CREATE INDEX idx_roster_student_number ON classroom_roster_entries (student_number);

CREATE TABLE assignments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id bigint NOT NULL,
    course_name varchar(100) NOT NULL,
    due_at timestamp(6) with time zone NOT NULL,
    instructions oid NOT NULL,
    published_at timestamp(6) with time zone NOT NULL,
    status varchar(20) NOT NULL,
    title varchar(240) NOT NULL,
    ai_declaration_required boolean,
    ai_policy varchar(30),
    appeal_allowed boolean,
    source_declaration_required boolean,
    submission_format varchar(20)
);

CREATE TABLE assignment_rubrics (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id bigint NOT NULL,
    description varchar(400) NOT NULL,
    display_order integer NOT NULL,
    name varchar(100) NOT NULL,
    points integer NOT NULL
);
CREATE INDEX idx_assignment_rubrics_assignment
    ON assignment_rubrics (assignment_id, display_order);

CREATE TABLE submissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id bigint NOT NULL,
    assignment_title varchar(240) NOT NULL,
    attachment_name varchar(160) NOT NULL,
    attempt_number integer NOT NULL,
    content oid NOT NULL,
    course_name varchar(100) NOT NULL,
    due_at timestamp(6) with time zone NOT NULL,
    review_status varchar(20) NOT NULL,
    reviewed_at timestamp(6) with time zone,
    student_account_id bigint NOT NULL,
    student_name varchar(80) NOT NULL,
    student_number varchar(40) NOT NULL,
    submitted_at timestamp(6) with time zone NOT NULL,
    word_count integer NOT NULL,
    ai_scope oid,
    ai_tools oid,
    ai_usage varchar(40),
    collaboration_declaration oid,
    integrity_confirmed boolean,
    source_declaration oid
);

CREATE TABLE submission_attachments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attachment_kind varchar(20) NOT NULL,
    content_type varchar(120) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    file_size bigint NOT NULL,
    original_name varchar(240) NOT NULL,
    stored_name varchar(240) NOT NULL,
    submission_id bigint NOT NULL
);
CREATE INDEX idx_submission_attachments_submission
    ON submission_attachments (submission_id);

CREATE TABLE review_drafts (
    submission_id bigint PRIMARY KEY,
    content oid NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    revision bigint NOT NULL,
    title varchar(200) NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL
);

CREATE TABLE collaborator_review_drafts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content oid NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    reviewer_account_id bigint NOT NULL,
    revision bigint NOT NULL,
    submission_id bigint NOT NULL,
    title varchar(200) NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uk_collaborator_review_draft UNIQUE (submission_id, reviewer_account_id)
);
CREATE INDEX idx_collaborator_review_submission
    ON collaborator_review_drafts (submission_id);

CREATE TABLE review_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_count integer NOT NULL,
    content oid NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    submission_id bigint NOT NULL,
    title varchar(200) NOT NULL,
    trigger_type varchar(20) NOT NULL,
    version_number bigint NOT NULL
);
CREATE INDEX idx_review_versions_submission
    ON review_versions (submission_id, version_number);

CREATE TABLE review_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    detail varchar(240) NOT NULL,
    event_type varchar(40) NOT NULL,
    occurred_at timestamp(6) with time zone NOT NULL,
    submission_id bigint NOT NULL,
    actor_account_id bigint,
    actor_name varchar(80)
);
CREATE INDEX idx_review_events_submission
    ON review_events (submission_id, occurred_at);

CREATE TABLE review_issues (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) with time zone NOT NULL,
    evidence_quote oid NOT NULL,
    rubric_name varchar(100) NOT NULL,
    submission_id bigint NOT NULL,
    teacher_note oid NOT NULL
);
CREATE INDEX idx_review_issues_rubric ON review_issues (rubric_name);
CREATE INDEX idx_review_issues_submission ON review_issues (submission_id);

CREATE TABLE review_scores (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) with time zone NOT NULL,
    final_points integer,
    max_points integer NOT NULL,
    rubric_id bigint NOT NULL,
    rubric_name varchar(100) NOT NULL,
    submission_id bigint NOT NULL,
    suggested_points integer NOT NULL,
    suggestion oid NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uk_review_scores_submission_rubric UNIQUE (submission_id, rubric_id)
);
CREATE INDEX idx_review_scores_submission ON review_scores (submission_id);

CREATE TABLE integrity_flags (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category varchar(40) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    evidence oid NOT NULL,
    reason oid NOT NULL,
    resolved_at timestamp(6) with time zone,
    severity varchar(20) NOT NULL,
    status varchar(20) NOT NULL,
    submission_id bigint NOT NULL
);
CREATE INDEX idx_integrity_flags_submission ON integrity_flags (submission_id);

CREATE TABLE appeals (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) with time zone NOT NULL,
    reason oid NOT NULL,
    requested_resolution oid,
    responded_at timestamp(6) with time zone,
    status varchar(20) NOT NULL,
    student_id bigint NOT NULL,
    submission_id bigint NOT NULL,
    teacher_response oid
);
CREATE INDEX idx_appeals_status ON appeals (status);
CREATE INDEX idx_appeals_submission ON appeals (submission_id);

CREATE TABLE lesson_plans (
    assignment_id bigint PRIMARY KEY,
    content oid NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    revision bigint NOT NULL,
    title varchar(240) NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL
);

CREATE TABLE ai_provider_settings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    active boolean NOT NULL,
    base_url varchar(300) NOT NULL,
    encrypted_api_key oid NOT NULL,
    key_suffix varchar(12) NOT NULL,
